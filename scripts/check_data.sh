#!/usr/bin/env bash
# =============================================================================
# check_data.sh — 数据完整性校验阶段
#
# 检查已保存的 K 线 JSONL 文件是否存在、行数是否正确、日期范围是否合理。
#
# 用法:
#   ./scripts/check_data.sh
#
# 环境变量:
#   ALPHA101_DATA_ROOT  数据根目录 (默认 ./data)
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
cd "$PROJECT_DIR"

# ---------- 参数解析 ----------
while [[ $# -gt 0 ]]; do
    case "$1" in
        -h|--help)
            head -10 "$0" | tail -8
            exit 0
            ;;
        *)
            echo "错误: 未知参数 '$1'" >&2
            exit 1
            ;;
    esac
done

# ---------- 执行 ----------
echo "=========================================="
echo "  阶段 4: 数据完整性校验 (Check Data)"
echo "=========================================="
echo "------------------------------------------"
python -m alpha101_factory.cli check

echo "=========================================="
echo "  校验阶段完成"
echo "=========================================="
